    f.write("    assignments = db.execute(\n")
    f.write("        select(JudgeAssignment).where(JudgeAssignment.event_id == event_id)\n")
    f.write("    ).scalars().all()\n")
    f.write("    total = len(assignments)\n")
    f.write("    completed = 0\n")
    f.write("    in_progress = 0\n")
    f.write("    unstarted = 0\n")
    f.write("    batch_stats = {}\n")
    f.write("    for assignment in assignments:\n")
    f.write("        review = db.execute(\n")
    f.write("            select(Review).where(Review.assignment_id == assignment.id)\n")
    f.write("        ).scalar_one_or_none()\n")
    f.write("    batch_id = assignment.batch_id or 0\n")
    f.write("    if batch_id not in batch_stats:\n")
    f.write("        batch_stats[batch_id] = {\"total\": 0, \"completed\": 0, \"in_progress\": 0, \"unstarted\": 0}\n")
    f.write("    batch_stats[batch_id][\"total\"] += 1\n")
    f.write("    if review and review.status == ReviewStatus.SUBMITTED:\n")
    f.write("        completed += 1\n")
    f.write("        batch_stats[batch_id][\"completed\"] += 1\n")
    f.write("    elif review and review.status in [ReviewStatus.DRAFT, ReviewStatus.IN_PROGRESS]:\n")
    f.write("        in_progress += 1\n")
    f.write("        batch_stats[batch_id][\"in_progress\"] += 1\n")
    f.write("    else:\n")
    f.write("        unstarted += 1\n")
    f.write("        batch_stats[batch_id][\"unstarted\"] += 1\n")
    f.write("    batches = db.execute(\n")
    f.write("        select(ReviewBatch).where(ReviewBatch.event_id == event_id)\n")
    f.write("    ).scalars().all()\n")
    f.write("    batch_names = {b.id: b.name for b in batches}\n")
    f.write("    batch_names[0] = \"Unbatched\"\n")
    f.write("    batch_progress = []\n")
    f.write("    for batch_id, stats in batch_stats.items():\n")
    f.write("        batch_progress.append(BatchProgressResponse(\n")
    f.write("            batch_id=batch_id,\n")
    f.write("            batch_name=batch_names.get(batch_id, f\"Batch {batch_id}\"),\n")
    f.write("            total_assignments=stats[\"total\"],\n")
    f.write("            completed_assignments=stats[\"completed\"],\n")
    f.write("            in_progress_assignments=stats[\"in_progress\"],\n")
    f.write("            unstarted_assignments=stats[\"unstarted\"],\n")
    f.write("            completion_rate=stats[\"completed\"] / stats[\"total\"] if stats[\"total\"] > 0 else 0\n")
    f.write("        ))\n")
    f.write("    return JudgingProgressResponse(\n")
