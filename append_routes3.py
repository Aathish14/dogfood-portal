    f.write("@router.get(\"/api/organizer/events/{event_id}/progress\", response_model=JudgingProgressResponse)\n")
    f.write("async def get_judging_progress(\n")
    f.write("    event_id: int,\n")
    f.write("    current_user: User = Depends(get_current_user_required),\n")
    f.write("    db: Session = Depends(get_db)\n")
