    f.write("    completed_reviews=completed,\n")
    f.write("    in_progress_reviews=in_progress,\n")
    f.write("    unstarted_reviews=unstarted,\n")
    f.write("    overall_completion_rate=completed / total if total > 0 else 0,\n")
    f.write("    batches=batch_progress\n")
